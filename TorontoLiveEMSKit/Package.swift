// swift-tools-version: 6.0

import PackageDescription

let package = Package(
    name: "TorontoLiveEMSKit",
    platforms: [
        // Deliberately below the app's own 26.6 deployment target. The app's
        // IPHONEOS_DEPLOYMENT_TARGET and MACOSX_DEPLOYMENT_TARGET govern what actually
        // ships, so a lower library minimum changes nothing — and a manifest declaring
        // tools-version 6.0 cannot name `.v26`, which arrived in a later
        // PackageDescription. The versions below are safe on any toolchain that
        // understands tools-version 6.0.
        .iOS(.v18),
        .macOS(.v15),
        .visionOS(.v1),
    ],
    products: [
        .library(
            name: "TorontoLiveEMSKit",
            targets: ["TorontoLiveEMSKit"]
        ),
    ],
    targets: [
        .target(
            name: "TorontoLiveEMSKit",
            resources: [
                // Data the app ships and the tests check: the Toronto forward sortation
                // area shapes, generated by scripts/make_postal_areas.py, and the fire
                // stations, police divisions and fire units, generated by
                // scripts/make_reference_data.py. Resources rather than code because they
                // are data; in the package rather than the app because the app target
                // cannot be tested at all, and these are worth testing — that they load,
                // that their coordinates land in Toronto, that there are 84 stations and
                // 19 divisions, and that a unit's station is a station number rather than
                // merely its digits.
                .process("Resources"),
            ]
        ),
        .testTarget(
            name: "TorontoLiveEMSKitTests",
            dependencies: ["TorontoLiveEMSKit"]
        ),
    ]
)
